export const uploadText: Record<Language, typeof ru> = { ru, kk }
export function uploadErrorText(code: string, language: Language | null): string {
  const t = uploadText[language ?? 'ru']
  if (code === 'FILE_TOO_LARGE') return t.size
  if (code === 'UNSUPPORTED_FILE_TYPE') return t.type
  if (['EMPTY_FILE', 'INVALID_FILE', 'INVALID_UPLOAD'].includes(code)) return t.invalid
  if (['UPLOAD_NOT_FOUND', 'SESSION_REQUIRED'].includes(code)) return t.expired
  if (['UPLOAD_LIMIT', 'AI_CALL_LIMIT'].includes(code)) return t.limit
  if (code === 'UPLOAD_TIMEOUT') return t.timeout
  if (code === 'INVALID_RESPONSE') return t.invalidResponse
  if (['UPLOAD_PROCESSOR_UNAVAILABLE', 'CATALOG_LOADING', 'CATALOG_UNAVAILABLE', 'BACKEND_UNAVAILABLE'].includes(code)) return t.unavailable
  return t.error
}
